export function getEstimatedRoadMinutes(fromId: string, toId: string): number {
  if (fromId === toId) return 20;
  return ROAD_MINUTES_MATRIX[fromId]?.[toId] ?? ROAD_MINUTES_MATRIX[toId]?.[fromId] ?? 90;
}

export function formatTravelDuration(minutes: number): string {
  if (minutes <= 0) return 'On-site · 0 min transit';
  if (minutes < 60) return `~${minutes} min road/walk`;
  const hrs = Math.floor(minutes / 60);
  const mins = minutes % 60;
  return mins === 0 ? `~${hrs} hr scenic drive` : `~${hrs} hr ${mins} min scenic drive`;
}

